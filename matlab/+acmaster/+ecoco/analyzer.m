function [retval,id] = analyzer(params,id)
% ecoco.analyzer parameters: data orbit9 window dt step delinear red pad sr1 sr2 srstep nsim adjust method fmaxdata main_unit_selection calcMode maxFrequency seed anchorFraction options(ProgressFcn,SeparateFinalPanel,Verbose,InterleavedWindowMode,InterleavedStepDepth,ECOCOWindowMode,ECOCOStepDepth,ECOCOCenterLimits,BlockedConsensusPolicy,CrossfitConsensus).
% Source: https://github.com/mingsongli/acycle/blob/dcba4279168745b563e0535b954297023dd62fc7/code/corrcoef/ecoco.m
if nargin < 2, id = []; end
[retval,id] = accompat.masterInvoke('ecoco-v3.1.1+dcba427/analyzer',params,id,@execute);
end

function r = execute(p)
accompat.requireFields(p.options,{'ProgressFcn','SeparateFinalPanel','Verbose','InterleavedWindowMode','InterleavedStepDepth','ECOCOWindowMode','ECOCOStepDepth','ECOCOCenterLimits','BlockedConsensusPolicy','CrossfitConsensus'});
[prt_sr, out_depth, out_ecc, out_ep, out_eci, out_ecoco, out_ecocorb, out_norbit, sr_p, ecoDetails] = ecoco( ...
    p.data, [], p.orbit9, p.window, p.dt, p.step, p.delinear, p.red, p.pad, p.sr1, p.sr2,  ...
    p.srstep, p.nsim, p.adjust, [], 0, p.method, p.fmaxdata, p.main_unit_selection, p.calcMode,  ...
    p.maxFrequency, p.seed, p.anchorFraction, 'ProgressFcn',p.options.ProgressFcn,  ...
    'SeparateFinalPanel',p.options.SeparateFinalPanel, 'Verbose',p.options.Verbose,  ...
    'InterleavedWindowMode',p.options.InterleavedWindowMode,  ...
    'InterleavedStepDepth',p.options.InterleavedStepDepth,  ...
    'ECOCOWindowMode',p.options.ECOCOWindowMode, 'ECOCOStepDepth',p.options.ECOCOStepDepth,  ...
    'ECOCOCenterLimits',p.options.ECOCOCenterLimits,  ...
    'BlockedConsensusPolicy',p.options.BlockedConsensusPolicy,  ...
    'CrossfitConsensus',p.options.CrossfitConsensus);
r = struct();
r.prt_sr = prt_sr;
r.out_depth = out_depth;
r.out_ecc = out_ecc;
r.out_ep = out_ep;
r.out_eci = out_eci;
r.out_ecoco = out_ecoco;
r.out_ecocorb = out_ecocorb;
r.out_norbit = out_norbit;
r.sr_p = sr_p;
r.ecoDetails = ecoDetails;
end
