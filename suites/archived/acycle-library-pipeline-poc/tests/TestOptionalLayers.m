classdef TestOptionalLayers < matlab.unittest.TestCase
    % SPDX-License-Identifier: GPL-3.0-or-later

    methods (TestClassSetup)
        function addPaths(testCase)
            root = fileparts(fileparts(mfilename('fullpath')));
            testCase.applyFixture( ...
                matlab.unittest.fixtures.PathFixture(fullfile(root,'matlab')));
            testCase.applyFixture( ...
                matlab.unittest.fixtures.PathFixture( ...
                fullfile(root,'matlab','compat')));
            testCase.applyFixture( ...
                matlab.unittest.fixtures.PathFixture(fullfile(root,'examples')));
        end
    end

    methods (Test)
        function staticPlotterRendersSuppliedResults(testCase)
            pipeline = TestOptionalLayers.makePipeline();
            [fig,graphics] = acycle.plot.showPipeline(pipeline,struct( ...
                'Visible','off','WidthInches',9,'HeightInches',3));
            cleanup = onCleanup(@() close(fig));

            testCase.verifyTrue(isgraphics(fig));
            testCase.verifyTrue(isgraphics(graphics.Spectrum));
            testCase.verifyEqual(fig.Position(3:4),[9,3],'AbsTol',1e-12);
            clear cleanup
        end

        function outsideCaptureSeesApiPrints(testCase)
            coordinate = (0:0.5:100)';
            data = [coordinate,sin(2*pi*0.05*coordinate)];
            parameters = struct( ...
                'LowerFrequency',0.04, ...
                'UpperFrequency',0.06, ...
                'Verbose',true);
            [filtered,~,record] = acycle.run.capture( ...
                @acycle.core.fixedBandpass,{data,parameters},struct( ...
                    'Operation','test-bandpass', ...
                    'Parameters',parameters));

            testCase.verifyEqual(record.Status,'succeeded');
            testCase.verifyNotEmpty(strfind(record.Transcript,'Acycle core API'));
            testCase.verifyEqual(size(filtered),size(data));
        end

        function legacyShimMatchesRelocatedEngine(testCase)
            coordinate = (0:0.5:100)';
            data = [coordinate,sin(2*pi*0.05*coordinate)];
            options = struct( ...
                'method','gaussian', ...
                'lower_frequency',0.04, ...
                'upper_frequency',0.06);
            [legacyResult,legacyMeta] = acycleBandpassFilter(data,options);
            [engineResult,engineMeta] = ...
                acycle.core.engine.acycleBandpassFilter(data,options);

            testCase.verifyEqual(legacyResult,engineResult);
            testCase.verifyEqual(legacyMeta,engineMeta);
        end
    end

    methods (Static, Access=private)
        function pipeline = makePipeline()
            coordinate = (0:0.5:100)';
            input = [coordinate,sin(2*pi*0.05*coordinate)];
            [spectrum,spectrumInfo] = acycle.core.powerSpectrum( ...
                input,struct('Method','periodogram','Verbose',false));
            [filtered,filterInfo] = acycle.core.fixedBandpass( ...
                input,struct( ...
                    'LowerFrequency',0.04, ...
                    'UpperFrequency',0.06, ...
                    'Verbose',false));
            pipeline = struct( ...
                'Input',input, ...
                'Regular',input, ...
                'Spectrum',spectrum, ...
                'Filtered',filtered, ...
                'SpectrumInfo',spectrumInfo, ...
                'FilterInfo',filterInfo);
        end
    end
end

